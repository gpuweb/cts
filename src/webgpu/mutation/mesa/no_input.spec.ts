export const description = `
Execution tests that read no input, found by mutation testing Mesa.

Each test is a compute shader generated by the WGSL fuzzer wgslsmith and then reduced
automatically. They were found by mutation testing a shader compiler: each program produces
different output when a specific bug is injected into the compiler, and no existing CTS test
detected that bug.

Each shader writes its result to a storage buffer at @group(0) @binding(1).
Buffers are given as bytes, in the form the fuzzer reports them, with a comment showing the
values of each struct member.

Test names are shader_ followed by the first 8 hex digits of the SHA-256 hash of the
shader text. kMutations records, for each test, the implementation that was mutated to find it
and where the mutation was.
`;

import { makeTestGroup } from '../../../common/framework/test_group.js';
import { AllFeaturesMaxLimitsGPUTest, GPUTest } from '../../gpu_test.js';
import { Mutation } from '../mutation_info.js';

export const g = makeTestGroup(AllFeaturesMaxLimitsGPUTest);

/**
 * For each test: the packages used to find it, and the mutation that it detects. Each entry is
 * added just above its test.
 */
export const kMutations: Record<string, Mutation[]> = {};

/**
 * Runs a shader (entry point `main`, one invocation) and checks the contents of its output
 * buffer.
 *
 * @param t The test object
 * @param buffers `output`: the expected bytes of the storage buffer at @group(0) @binding(1).
 * The buffer starts zero-filled, so padding bytes are expected to be 0.
 * @param wgsl The shader
 */
function runGeneratedTest(t: GPUTest, buffers: { output: Uint8Array }, wgsl: string) {
  const pipeline = t.device.createComputePipeline({
    layout: 'auto',
    compute: {
      module: t.device.createShaderModule({ code: wgsl }),
      entryPoint: 'main',
    },
  });

  // New buffers are zero-filled.
  const outputBuffer = t.createBufferTracked({
    size: buffers.output.byteLength,
    usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_SRC,
  });
  const bindGroup = t.device.createBindGroup({
    layout: pipeline.getBindGroupLayout(0),
    entries: [{ binding: 1, resource: { buffer: outputBuffer } }],
  });

  // Run the shader.
  const encoder = t.device.createCommandEncoder();
  const pass = encoder.beginComputePass();
  pass.setPipeline(pipeline);
  pass.setBindGroup(0, bindGroup);
  pass.dispatchWorkgroups(1);
  pass.end();
  t.queue.submit([encoder.finish()]);

  t.expectGPUBufferValuesEqual(outputBuffer, buffers.output);
}

