export const description = `
Execution tests that read a uniform buffer, found by mutation testing Mesa.

Each case is a compute shader generated by the WGSL fuzzer WGSLsmith and then reduced
automatically. They were found by mutation testing a shader compiler: each program produces
different output when a specific change is injected into the compiler, and no existing CTS test
detected that change.

Each shader writes its result to a storage buffer at @group(0) @binding(1).
Each also reads a uniform buffer at @group(0) @binding(0), filled with the fuzzer's random
input (cut to the size of the binding).
Input and expected output are given as bytes, in the form the fuzzer reports them,
with a comment showing the values of each struct member.

Case names are "shader_" followed by the first 8 hex digits of the SHA-256 hash of the
shader text. kTestData holds each case's shader, its input and expected output, and the
mutation it detects.
`;

import { makeTestGroup } from '../../../../../common/framework/test_group.js';
